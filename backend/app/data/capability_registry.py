def list_capabilities() -> list[dict]:
    out = []
    for c in ALL_CAPABILITIES.values():
        out.append({
            "key": c.key,
            "name": c.name,
            "category": c.category,
            "widget": c.widget,
            "agent_id": c.agent_id,
            "flutter_pkg": c.flutter_pkg,
            "keywords": list(c.keywords),
            "labels": c.resolved_labels(),
        })
    return sorted(out, key=lambda x: (x["category"], x["key"]))


