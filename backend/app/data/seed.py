def build_office_scenarios() -> list[dict]:
    scenarios = []
    idx = 1
    for group in OFFICE_GROUPS:
        for name in group["items"]:
            scenarios.append(
                {
                    "id": f"office-{idx:03d}",
                    "name": name,
                    "category": group["category"],
                    "category_icon": group["icon"],
                    "agent": group["agent"],
                    "type": "office",
                    "auto_generate": "FormWidget / ChatWidget / ListWidget + workflow seed",
                }
            )
            idx += 1
    return scenarios


def build_industry_scenarios() -> list[dict]:
    scenarios = []
    idx = 1
    for pack in INDUSTRY_PACKS:
        for scene in pack.get("scenes") or []:
            scenarios.append(
                {
                    "id": f"industry-{idx:03d}",
                    "name": scene["name"],
                    "category": scene["category"],
                    "pack_key": pack["key"],
                    "pack_name": pack["name"],
                    "pack_icon": pack["icon"],
                    "pack_color": pack["color"],
                    "problem": scene["problem"],
                    "pages": scene["pages"],
                    "standard": scene["standard"],
                    "agent": scene["agent"],
                    "type": "industry",
                }
            )
            idx += 1
    return scenarios


