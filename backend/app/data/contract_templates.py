def get_template(key: str) -> dict | None:
    return next((t for t in CONTRACT_TEMPLATES if t["key"] == key), None)


def apply_parties(body: str, parties: dict) -> str:
    out = body
    out = out.replace("{{title}}", parties.get("title", "合同"))
    out = out.replace("{{party_a}}", parties.get("party_a", "甲方"))
    out = out.replace("{{party_b}}", parties.get("party_b", "乙方"))
    return out
